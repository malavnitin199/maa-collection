/**
 * The key for a `codeWordProblem()` message (src/lib/price-code.ts), so the settings
 * form and service can show it in the person's language; undefined for any other text.
 */
export function codeWordProblemKey(problem: string): 'own.err.codeWordLength' | 'own.err.codeWordRepeat' | undefined {
  if (problem === ownerEn['own.err.codeWordLength']) return 'own.err.codeWordLength';
  if (problem === ownerEn['own.err.codeWordRepeat']) return 'own.err.codeWordRepeat';
  return undefined;
}
